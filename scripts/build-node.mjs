#!/usr/bin/env node
// Bundles a Node app into a single ESM file.
// Workspace packages (@jarvis/*) ship TypeScript source, so they are inlined; every other bare
// import stays external and resolves from the app's own node_modules at runtime.
//
// usage: node scripts/build-node.mjs <entry.ts> <outfile.js>   (paths relative to the app)
import { build } from 'esbuild';
import { resolve } from 'node:path';

const [entry, outfile] = process.argv.slice(2);
if (!entry || !outfile) {
  console.error('usage: build-node.mjs <entry> <outfile>');
  process.exit(1);
}

/** @type {import('esbuild').Plugin} */
const externalizeDependencies = {
  name: 'externalize-dependencies',
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /^[^./]/ }, (args) => {
      if (args.path.startsWith('@jarvis/')) return undefined; // inline workspace packages
      return { path: args.path, external: true };
    });
  },
};

await build({
  entryPoints: [resolve(entry)],
  outfile: resolve(outfile),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  sourcemap: true,
  logLevel: 'info',
  plugins: [externalizeDependencies],
  banner: { js: '// Generated by scripts/build-node.mjs — do not edit.' },
});
